package com.dima.fooddelivery.common.web;

import org.slf4j.MDC;

import java.util.Optional;

/**
 * Сквозной идентификатор запроса.
 *
 * <p>Решает задачу, которая появляется ровно тогда, когда обработка перестаёт быть
 * последовательной. Один вызов API оставляет следы в нескольких местах: строки в логе,
 * запись в журнале аудита, событие в outbox, сообщение в Kafka, уведомление, созданное
 * потребителем через секунду и в другом потоке. Без общей метки связать их между собой
 * можно только по времени, а время врёт: под нагрузкой в одну секунду укладываются сотни
 * запросов.
 *
 * <p>Метка живёт в {@link MDC} — это ThreadLocal, который logback подставляет в каждую
 * строку лога сам, без передачи параметром через все слои. Отсюда же следует главное
 * ограничение: за границу потока MDC не переходит. Поэтому на каждой асинхронной границе
 * метку приходится переносить руками — в outbox её кладёт слушатель, в Kafka она едет
 * заголовком, а на стороне потребителя её восстанавливают в MDC заново.
 */
public final class RequestContext {

    /** Заголовок принимается снаружи: клиент вправе задать свою метку, чтобы сшить её со своими логами. */
    public static final String CORRELATION_ID_HEADER = "X-Correlation-Id";

    /**
     * Заголовок только исходящий. Принимать его из запроса нельзя: пользователь определяется
     * по подписанному токену, и доверять этому же значению из заголовка означало бы дать
     * любому клиенту назваться кем угодно.
     */
    public static final String USER_ID_HEADER = "X-User-Id";

    public static final String CORRELATION_ID_MDC_KEY = "correlationId";
    public static final String USER_ID_MDC_KEY = "userId";

    /**
     * Ограничение длины. Значение приходит снаружи и попадает и в лог, и в базу, поэтому
     * его размер должен быть предсказуем: колонка ограничена, а строка лога не должна
     * распухать от чужого мусора.
     */
    public static final int MAX_LENGTH = 64;

    private RequestContext() {
    }

    /**
     * @return метка текущего потока или пустое значение, если её там нет
     *         (фоновая задача, поток планировщика, потребитель до восстановления)
     */
    public static Optional<String> correlationId() {
        return Optional.ofNullable(MDC.get(CORRELATION_ID_MDC_KEY));
    }
}
