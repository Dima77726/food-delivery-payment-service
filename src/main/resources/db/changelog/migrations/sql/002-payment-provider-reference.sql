-- Идентификатор платежа у внешнего провайдера (для Stripe — PaymentIntent, pi_...).
--
-- Нужен возврату: вернуть деньги можно только по платежу у провайдера, а не по нашему заказу.
-- NULL у платежей, которые провайдер не видел: наличные при получении, заглушка шлюза и все
-- платежи, проведённые до этой миграции. Возврат по такому платежу ничего не делает у провайдера.
ALTER TABLE payment ADD COLUMN IF NOT EXISTS provider_reference VARCHAR(100);

COMMENT ON COLUMN payment.provider_reference IS 'Идентификатор платежа у внешнего провайдера; NULL, если провайдер платёж не видел';
